def main():
    banner("Experiment 4 - learning (alpha, beta) from the marginal likelihood")

    rows, fits, paths, multis, spread, lr_mirror = [], {}, {}, {}, {}, {}

    print("\n 1. Autograd vs central differences on log p(y | alpha, beta)")
