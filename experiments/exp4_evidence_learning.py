# --------------------------------------------------------------------------- #
def new_gp(alpha, beta, learn=NUISANCE, n=N):
    return JacobiGP(N=n, spectrum=SPECTRUM, alpha=alpha, beta=beta, lengthscale=0.4,
                    sigma2=1.0, noise=NOISE, learn=learn, dtype=DT)


def penalty(params, sd=PRIOR_SD):
    """N(0, sd^2) on the unconstrained (raw softplus) coordinates of alpha, beta.

    In constrained coordinates this is a prior whose density vanishes at alpha = -1 while
    its support is the whole admissible half-plane, i.e. a logarithmic barrier at the
    singular edge of the parameter space - exactly what the raw evidence lacks.  With
    sd = 2 it puts 95% of its mass on alpha, beta in (-0.98, 2.9).
    """
    return 0.5 * ((params.raw_alpha / sd) ** 2 + (params.raw_beta / sd) ** 2)


def objective(gp, X, y, penalise=True):
    v = gp.log_marginal_likelihood(X, y)
    return v - penalty(gp.params) if penalise else v


def fit_track(gp, X, y, penalise=True, adam_steps=500, lr=0.05, lbfgs_iters=150, snap_every=None):
    """Adam warm-up + L-BFGS on the (penalised) evidence; records the (alpha, beta, obj) path.

    If the iterates walk out of the admissible half-plane the objective raises (see
    `_cholesky_spd`); rather than losing the run, the trajectory is closed with a
    `breakdown` entry holding the LAST ADMISSIBLE iterate, and no exception escapes.
    """
    traj = []
    good = [gp.params.as_dict()]          # last iterate at which the objective evaluated

    def evaluate():
        v = objective(gp, X, y, penalise)  # may raise -> `good` is then still the previous one
        good[0] = gp.params.as_dict()
        return v

    def snap(tag):
        d = gp.params.as_dict()
        lml = float(gp.log_marginal_likelihood(X, y).detach())
        pen = float(penalty(gp.params).detach()) if penalise else 0.0
        traj.append(dict(tag=tag, **d, obj=lml - pen, lml=lml))

    params = [p for p in gp.parameters() if p.requires_grad]
    snap("init")
    if not params:
        return traj
    every = snap_every or max(1, adam_steps // 40)
    try:
        if adam_steps:
            opt = torch.optim.Adam(params, lr=lr)
            for it in range(adam_steps):
                opt.zero_grad()
                (-evaluate()).backward()
                opt.step()
                if (it + 1) % every == 0:
                    snap(f"adam{it + 1}")
        if lbfgs_iters:
            opt = torch.optim.LBFGS(params, lr=1.0, max_iter=lbfgs_iters, history_size=12,
                                    tolerance_grad=1e-12, tolerance_change=1e-14,
                                    line_search_fn="strong_wolfe")

            def closure():
                opt.zero_grad()
                loss = -evaluate()
                loss.backward()
                return loss

            opt.step(closure)
            snap("lbfgs")
    except (ValueError, RuntimeError) as exc:
        traj.append(dict(tag="breakdown", breakdown=f"{type(exc).__name__}: {str(exc)[:200]}",
                         **good[0]))
    return traj


def rms(v):
    v = torch.as_tensor(v)
    return float(torch.sqrt((v ** 2).mean())) if v.numel() else float("nan")


def score(gp, fn, X, y):
    """Test error on a dense grid (truth known), split by region, + the prior mechanism."""
    truth = fn(XS)
    mean, var, _ = gp.predict(XS, gp.posterior(X, y), noise=False)
    e = (mean - truth).detach()
    d = gp.params.as_dict()
    prior_sd = gp.predict(XS)[1].sqrt().detach()
    return dict(rmse=rms(e), edge_rmse=rms(e[XS.abs() > EDGE]),
                interior_rmse=rms(e[XS.abs() <= EDGE - 0.05]),
                left_edge_rmse=rms(e[XS < -0.99]), right_edge_rmse=rms(e[XS > 0.99]),
                lml=float(gp.log_marginal_likelihood(X, y).detach()),
                map=float(objective(gp, X, y).detach()),
                alpha=d["alpha"], beta=d["beta"], alpha_beta_sum=d["alpha"] + d["beta"],
                lengthscale=d["lengthscale"], sigma2=d["sigma2"], noise=d["noise"],
                prior_sd_left=float(prior_sd[0]), prior_sd_right=float(prior_sd[-1]),
                prior_sd_centre=float(prior_sd[XS.abs() < 0.02].mean()))


def data_for(tname):
    return make_data(TARGETS[tname], M=M, noise=NOISE, seed=SEED, mode="uniform",
                     domain=(-EDGE, EDGE))


# --------------------------------------------------------------------------- #
# PART 1 - is the evidence really differentiable in (alpha, beta)?
# --------------------------------------------------------------------------- #
def gradient_check(X, y, alpha=1.3, beta=-0.4, eps=1e-4):
    """Autograd dLML/d(alpha, beta) through the recurrence vs. central finite differences."""
    out = {}
    for what in ("alpha", "beta"):
        gp = new_gp(alpha, beta, learn=("alpha", "beta"))
        raw = getattr(gp.params, f"raw_{what}")
        (g_raw,) = torch.autograd.grad(gp.log_marginal_likelihood(X, y), raw)
        # d alpha / d raw = softplus'(raw) = sigmoid(raw)  ->  chain rule back to dLML/dalpha
        auto = float(g_raw.detach()) / float(torch.sigmoid(raw.detach()))

        def lml_at(delta):
            aa = alpha + (delta if what == "alpha" else 0.0)
            bb = beta + (delta if what == "beta" else 0.0)
            return float(new_gp(aa, bb, learn=()).log_marginal_likelihood(X, y).detach())

        fd = (lml_at(eps) - lml_at(-eps)) / (2 * eps)
        out[f"dLML_d{what}_autograd"] = auto
        out[f"dLML_d{what}_central_difference"] = fd
        out[f"rel_error_{what}"] = abs(auto - fd) / max(abs(fd), 1e-12)
    return out


# --------------------------------------------------------------------------- #
# PART 2 - the pure-evidence degeneracy
# --------------------------------------------------------------------------- #
def ridge_scan(tname="steep_right", alphas=(0.0, 1.0, 2.0, 4.0, 6.0, 8.0, 12.0)):
    """Fix alpha, put beta at -0.9, profile ls/sigma2/noise by *pure* ML, score by test error."""
    fn, X, y = TARGETS[tname], *data_for(tname)
    rows = []
    for a in alphas:
        try:
            gp = new_gp(a, -0.9, learn=NUISANCE)
            fit_track(gp, X, y, penalise=False, adam_steps=400, lbfgs_iters=100)
            r = score(gp, fn, X, y) | dict(alpha_fixed=a, beta_fixed=-0.9, target=tname,
                                           note="ok")
        except (ValueError, RuntimeError) as exc:          # the singular corner
            r = dict(alpha_fixed=a, beta_fixed=-0.9, target=tname, lml=float("nan"),
                     rmse=float("nan"), sigma2=float("nan"), map=float("nan"),
                     note=f"breakdown: {type(exc).__name__}: {str(exc)[:120]}")
        rows.append(r)
        print(f"    α={a:5.1f}  lml={r['lml']:8.3f}  σ²={r['sigma2']:.2e}  "
              f"test rmse={r['rmse']:.4f}   {r['note'][:60]}")
    ok = [r for r in rows if np.isfinite(r["lml"])]
    best_lml = max(ok, key=lambda r: r["lml"])
    best_rmse = min(ok, key=lambda r: r["rmse"])
    print(f"    -> evidence prefers α={best_lml['alpha_fixed']:g} (rmse {best_lml['rmse']:.4f}), "
          f"test error prefers α={best_rmse['alpha_fixed']:g} (rmse {best_rmse['rmse']:.4f}); "
          f"σ² shrinks by {ok[0]['sigma2'] / best_lml['sigma2']:.0f}x")
    return dict(target=tname, rows=rows, best_lml=best_lml, best_rmse=best_rmse)


def gp_at(d):
    """Rebuild a frozen GP from a recorded parameter dict (used after a breakdown)."""
    return frozen_gp(d["alpha"], d["beta"], d)


def frozen_gp(alpha, beta, nuisance):
    """A GP with (alpha, beta) given and ls/sigma2/noise taken from a recorded dict."""
    gp = new_gp(alpha, beta, learn=())
    with torch.no_grad():
        gp.params.raw_lengthscale.fill_(math.log(nuisance["lengthscale"]))
        gp.params.raw_sigma2.fill_(math.log(nuisance["sigma2"]))
        gp.params.raw_noise.fill_(math.log(nuisance["noise"]))
    return gp


def pure_ml_run(tname=PRIMARY, adam_steps=800, lbfgs_iters=200):
    """All five hyper-parameters free, NO prior: what happens on its own?"""
    fn, X, y = TARGETS[tname], *data_for(tname)
    gp = new_gp(0.0, 0.0, learn=("alpha", "beta", *NUISANCE))
    traj = fit_track(gp, X, y, penalise=False, adam_steps=adam_steps, lbfgs_iters=lbfgs_iters)
    broke = traj[-1].get("breakdown")
    r = score(gp if broke is None else gp_at(traj[-1]), fn, X, y)
    r.update(target=tname, crashed=broke is not None, crash=broke or "",
             note=("walked off the admissible half-plane -> the design matrix lost rank"
                   if broke else "stayed admissible (but see the beta -> -1 drift)"),
             steps=len(traj))
    print(f"    pure ML on '{tname:12}': α={r['alpha']:8.4f} β={r['beta']:8.5f} "
          f"σ²={r['sigma2']:.2e} lml={r['lml']:8.2f} test rmse={r['rmse']:.4f}  [{r['note']}]")
    return r


# --------------------------------------------------------------------------- #
# PART 3 - profiled (penalised) evidence landscape over the (alpha, beta) plane
# --------------------------------------------------------------------------- #
def landscape(tname=PRIMARY, grid=None, adam_steps=250, lbfgs_iters=60):
    """At every (alpha, beta): profile ls/sigma2/noise by MAP; also record raw ML + test RMSE."""
    fn, X, y = TARGETS[tname], *data_for(tname)
    grid = grid if grid is not None else GRID
    Z = np.zeros((len(grid), len(grid)))          # penalised (MAP) objective
    Raw = np.zeros_like(Z)                        # raw evidence
    Rm = np.full_like(Z, np.nan)                  # test RMSE of the fit at that space
    for i, a in enumerate(grid):
        for j, b in enumerate(grid):
            gp = new_gp(a, b, learn=NUISANCE)
            fit_track(gp, X, y, penalise=True, adam_steps=adam_steps, lr=0.05,
                      lbfgs_iters=lbfgs_iters)
            Z[i, j] = float(objective(gp, X, y).detach())
            r = score(gp, fn, X, y)
            Raw[i, j], Rm[i, j] = r["lml"], r["rmse"]
        print(f"    row {i + 1}/{len(grid)} (α={a:5.2f}): best MAP {Z[:i + 1].max():.3f}, "
              f"best test rmse so far {np.nanmin(Rm[:i + 1]):.4f}")
    return grid, Z, Raw, Rm


