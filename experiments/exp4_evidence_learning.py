"""
Experiment 4 - Automated learning of the functional space from the evidence
===========================================================================
Hypothesis (AGENTS.md): "the optimal functional space (best alpha, beta) can be learned
directly from data via marginal likelihood maximisation" - the user never picks a Jacobi
family, the data do.  Everything that makes this possible lives in `basis.py`: the
orthonormal polynomials are generated by a symmetric three-term recurrence built out of
+ - * / sqrt lgamma, so Autograd differentiates the design matrix - and therefore the
evidence - with respect to alpha and beta themselves.  Part 1 of this script certifies
that derivative numerically.

THE TWIST (worth more than the headline): pure maximum likelihood over (alpha, beta) is
degenerate.  The admissible set {alpha > -1, beta > -1} is open, the weight
w = (1-x)^alpha (1+x)^beta is singular on its boundary, and the normalisation
h_n ~ 2^{a+b+1} G(a+1)G(b+1)/G(a+b+2) lets the basis amplitude absorb sigma^2, so the
evidence climbs a ridge on which sigma^2 -> 0.  Depending on the target the optimiser
either stops at a large-alpha / beta -> -1 point whose TEST error is 4x worse than the
MAP one, or walks into the corner alpha = beta = -1 where the design matrix loses rank
and the Cholesky fails.  The cure is the classical one: a weakly-informative prior on the
*unconstrained* (softplus) coordinates, i.e. MAP instead of ML.  With that one change the
optimum becomes interior, unique (6 initialisations agree to ~1e-7) and it tracks the
boundary signature of the data - which is the claim.

Protocol
--------
Data live in [-0.85, 0.85]; the two boundary layers stay *unsampled*, so the boundary
behaviour is something the likelihood must guess from the geometry of the prior.

       target          boundary signature                 predicted ML space
  1  ramp_right       flat & 0 at -1, growing at +1     alpha >  beta
  2  ramp_left        exact mirror of 1                 beta  >  alpha   (falsification)
  3  steep_right      flat & 0 at -1, JUMP at +1        alpha >> beta
  4  steep_left       exact mirror of 3                 beta  >> alpha
  5  vanishing        symmetric, 0 at BOTH edges        alpha = beta < 0 (clamp both)
  6  edge_support     symmetric, growing at BOTH edges  alpha = beta > alpha_5
  controls per target: fixed Legendre (alpha=beta=0), the deliberately mirrored space,
  a classical RBF-GP, and 6 multi-starts.

Checks 5 and 6 are not luck: if the data are invariant under x -> -x then the evidence is
invariant under alpha <-> beta, hence a unique ML space must have alpha = beta; and if
target 2 is the mirror of target 1 its ML pair must be the mirror pair.  Both are verified
to 2-3 digits.

Convention note (AGENTS.md tabulates it the other way round): with
w(x) = (1-x)^alpha (1+x)^beta, ALPHA acts on the RIGHT edge x = +1 and BETA on the LEFT.
"""

